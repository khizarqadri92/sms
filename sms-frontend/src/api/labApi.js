import client from "./client";
const B = "/laboratory";
const labApi = {
  meta:          ()           => client.get(B + "/meta"),
  dashboard:     ()           => client.get(B + "/dashboard"),
  labs:          (params)     => client.get(B + "/labs", { params }),
  lab:           (id)         => client.get(B + "/labs/" + id),
  createLab:     (d)          => client.post(B + "/labs", d),
  updateLab:     (id, d)      => client.put(B + "/labs/" + id, d),
  setStatus:     (id, status, reason) => client.post(B + "/labs/" + id + "/status", { status, reason }),
  setSupervisor: (id, user_id) => client.post(B + "/labs/" + id + "/supervisor", { user_id }),
  supervisors:   ()           => client.get(B + "/supervisors"),
  lookups:       (kind)       => client.get(B + "/lookups", { params: { kind } }),
  addLookup:     (d)          => client.post(B + "/lookups", d),
  editLookup:    (id, d)      => client.put(B + "/lookups/" + id, d),
  getSettings:   ()           => client.get(B + "/settings"),
  saveSettings:  (d)          => client.put(B + "/settings", d),
  // phase 2: equipment, issue & return, consumables, stock
  equipment:       (params)     => client.get(B + "/equipment", { params }),
  equipmentItem:   (id)         => client.get(B + "/equipment/" + id),
  addEquipment:    (d)          => client.post(B + "/equipment", d),
  editEquipment:   (id, d)      => client.put(B + "/equipment/" + id, d),
  equipmentAction: (id, d)      => client.post(B + "/equipment/" + id + "/action", d),
  issues:          (params)     => client.get(B + "/issues", { params }),
  issue:           (id)         => client.get(B + "/issues/" + id),
  requestIssue:    (d)          => client.post(B + "/issues", d),
  approveIssue:    (id, note)   => client.post(B + "/issues/" + id + "/approve", { note }),
  rejectIssue:     (id, note)   => client.post(B + "/issues/" + id + "/reject", { note }),
  cancelIssue:     (id)         => client.post(B + "/issues/" + id + "/cancel"),
  handOver:        (id, items)  => client.post(B + "/issues/" + id + "/issue", { items }),
  receiveBack:     (id, items, note) => client.post(B + "/issues/" + id + "/return", { items, note }),
  consumables:     (params)     => client.get(B + "/consumables", { params }),
  consumable:      (id)         => client.get(B + "/consumables/" + id),
  addConsumable:   (d)          => client.post(B + "/consumables", d),
  editConsumable:  (id, d)      => client.put(B + "/consumables/" + id, d),
  stockReceive:    (d)          => client.post(B + "/stock/receive", d),
  stockOut:        (d)          => client.post(B + "/stock/out", d),
  stockTransfer:   (d)          => client.post(B + "/stock/transfer", d),
  stockAdjust:     (d)          => client.post(B + "/stock/adjust", d),
  reverseTxn:      (id, reason) => client.post(B + "/stock/transactions/" + id + "/reverse", { reason }),
  transactions:    (params)     => client.get(B + "/stock/transactions", { params }),
  suppliers:       ()           => client.get(B + "/suppliers"),
  inventorySummary: ()          => client.get(B + "/inventory/summary"),
  dashboardCharts: ()           => client.get(B + "/dashboard/charts"),
  procurementItems: (q)         => client.get(B + "/procurement-items", { params: { q } }),
  grnPending:      ()           => client.get(B + "/grn-pending"),
  grnReceive:      (id, d)      => client.post(B + "/grn-pending/" + id + "/receive", d),
};
export default labApi;
